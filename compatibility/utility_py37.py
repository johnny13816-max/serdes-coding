def _truncate_keep_mass(p: Pmf1D, *, keep_mass: float) -> Pmf1D:
    """
    Return p truncated to keep the requested probability mass.

    Parameters
    ----------
    p:
        Input PMF to truncate.
    keep_mass:
        Probability mass target to keep, usually close to 1.
    """
    if not isinstance(p, Pmf1D):
        raise TypeError("p must be a Pmf1D.")

    keep_mass = float(keep_mass)
    if not np.isfinite(keep_mass) or keep_mass <= 0.0 or keep_mass > 1.0:
        raise ValueError("keep_mass must be finite and in (0, 1].")

    if keep_mass == 1.0:
        return p

    tail = 0.5 * (1.0 - keep_mass)
    cdf = p.cdf

    i0 = int(np.searchsorted(cdf, tail, side="left"))
    i1 = int(np.searchsorted(cdf, 1.0 - tail, side="left"))
    i0 = max(0, min(i0, len(p.pmf) - 1))
    i1 = max(i0, min(i1, len(p.pmf) - 1))

    p.pmf = Pmf1D._validate_mass(p.pmf[i0:i1 + 1])
    p.pmf = Pmf1D._validate_pmf(p.pmf / np.sum(p.pmf))
    p.st_idx += i0
    p.x_st = p.st_idx * p.dx
    return p

def _prune_fir_coeff(
    fir: np.ndarray,
    *,
    tap_abs_th: float = 0.0,
    max_taps: Optional[int] = None
) -> np.ndarray:
    """
    Return FIR taps after threshold and count pruning.

    Parameters
    ----------
    fir:
        1D FIR tap coefficients.
    tap_abs_th:
        Absolute tap threshold. Keep taps with abs(tap) >= tap_abs_th.
    max_taps:
        Maximum number of strongest taps to keep.
    """
    fir = np.asarray(fir, dtype=float)

    if fir.ndim != 1:
        raise ValueError("fir must be a 1D array.")

    if len(fir) == 0:
        raise ValueError("fir must contain at least one tap.")

    if not np.all(np.isfinite(fir)):
        raise ValueError("fir contains non-finite values.")

    tap_abs_th = float(tap_abs_th)
    if not np.isfinite(tap_abs_th) or tap_abs_th < 0:
        raise ValueError("tap_abs_th must be finite and non-negative.")

    if max_taps is not None:
        if not isinstance(max_taps, (int, np.integer)) or max_taps <= 0:
            raise ValueError("max_taps must be a positive integer or None.")
        max_taps = int(max_taps)

    max_abs = np.max(np.abs(fir))
    if max_abs == 0.0:
        return np.array([], dtype=float)

    keep = np.abs(fir) >= tap_abs_th

    if max_taps is not None and np.count_nonzero(keep) > max_taps:
        kept_indices = np.flatnonzero(keep)
        strongest = kept_indices[np.argsort(np.abs(fir[kept_indices]))[-max_taps:]]
        keep = np.zeros_like(keep, dtype=bool)
        keep[np.sort(strongest)] = True

    return fir[keep]

class Pmf1D:
    """
    One-dimensional probability mass function on a uniform x grid.

    The x-axis is represented by:
        x[k] = (st_idx + k) * dx

    Keep only dx, st_idx, and pmf in memory. The explicit x array is generated
    on demand by the x property.
    """

    def __init__(self, dx: float, st_idx: int, pmf: np.ndarray, unit: str = "", name: str = ""):
        """
        Build a PMF on a uniform grid.

        Parameters
        ----------
        dx:
            X-axis grid spacing.
        st_idx:
            Integer grid index of pmf[0].
        pmf:
            1D probability mass array; must be non-negative and sum to 1.
        unit:
            Optional x-axis unit label.
        name:
            Optional PMF name for debug / plotting.
        """
        self.dx = self._validate_dx(dx)
        self.st_idx = self._validate_st_idx(st_idx)
        self.x_st = self.st_idx * self.dx
        self.pmf = self._validate_pmf(pmf)
        self.unit = unit
        self.name = name

    @property
    def x(self) -> np.ndarray:
        "Don't save 'x' to save memory."
        return self.x_st + np.arange(len(self.pmf)) * self.dx

    @property
    def cdf(self) -> np.ndarray:
        "Don't save CDF to avoid cache invalidation in in-place operations."
        return np.cumsum(self.pmf)

    def plot(
        self,
        ax: object = None,
        save_path: str = "",
        *,
        quantity: str = "pmf",
        label: Optional[str] = None,
    ) -> object:
        """Plot probability mass or CDF using the PMF's native amplitude grid.

        Parameters
        ----------
        ax:
            Optional matplotlib axes. An externally supplied axes is not shown
            or closed unless ``save_path`` is also supplied.
        save_path:
            Optional output image path.
        quantity:
            ``"pmf"`` plots probability mass; ``"cdf"`` plots cumulative mass.
        label:
            Optional curve label for overlays.
        """
        if quantity not in {"pmf", "cdf"}:
            raise ValueError("quantity must be either 'pmf' or 'cdf'.")

        import matplotlib.pyplot as plt

        created_ax = ax is None
        if created_ax:
            _, ax = plt.subplots()

        values = self.pmf if quantity == "pmf" else self.cdf
        ax.plot(self.x, values, label=label or self.name or None)
        if label is not None or self.name:
            ax.legend()
        ax.set_xlabel(f"Amplitude ({self.unit or 'arb.'})")
        ax.set_ylabel("Probability mass" if quantity == "pmf" else "CDF")
        ax.set_title("PMF" if quantity == "pmf" else "PMF CDF")
        ax.grid(True)

        fig = ax.figure
        fig.tight_layout()
        if save_path:
            fig.savefig(save_path, bbox_inches="tight")
            if created_ax:
                plt.close(fig)
        elif created_ax:
            fig.canvas.draw_idle()
            plt.show()
        return ax

    # --------------------------------
    # validation
    # --------------------------------
    @staticmethod
    def _validate_dx(dx: float) -> float:
        """
        Validate x-axis grid spacing.

        Parameters
        ----------
        dx:
            Candidate grid spacing.
        """
        dx = float(dx)
        if not np.isfinite(dx) or dx <= 0:
            raise ValueError("dx must be a finite positive value.")
        return dx

    @staticmethod
    def _validate_st_idx(st_idx: int) -> int:
        """
        Validate integer start index.

        Parameters
        ----------
        st_idx:
            Candidate integer grid index.
        """
        if not isinstance(st_idx, (int, np.integer)):
            raise TypeError("st_idx must be an integer grid index.")
        return int(st_idx)

    @staticmethod
    def _validate_mass(mass: np.ndarray) -> np.ndarray:
        """
        Validate non-negative mass values without requiring sum == 1.

        Parameters
        ----------
        mass:
            Candidate 1D non-negative mass array.
        """
        mass = np.asarray(mass, dtype=float)

        if mass.ndim != 1:
            raise ValueError("mass must be a 1D array.")

        if len(mass) == 0:
            raise ValueError("mass must contain at least one point.")

        if not np.all(np.isfinite(mass)):
            raise ValueError("mass contains non-finite values.")

        if np.any(mass < 0):
            raise ValueError("mass must not contain negative probability mass.")

        return mass

    @staticmethod
    def _validate_pmf(pmf: np.ndarray, rtol: float = 1e-12, atol: float = 1e-15) -> np.ndarray:
        """
        Validate a complete probability mass function.

        Parameters
        ----------
        pmf:
            Candidate 1D probability mass array.
        rtol:
            Relative tolerance for sum(pmf) == 1.
        atol:
            Absolute tolerance for sum(pmf) == 1.
        """
        pmf = Pmf1D._validate_mass(pmf)

        total_mass = np.sum(pmf)
        if not np.isclose(total_mass, 1.0, rtol=rtol, atol=atol):
            raise ValueError(f"pmf must sum to 1. Got sum={total_mass}.")

        return pmf

    @staticmethod
    def _validate_scale(scale: float) -> float:
        """
        Validate x-axis scale factor.

        Parameters
        ----------
        scale:
            Candidate finite scale factor.
        """
        scale = float(scale)
        if not np.isfinite(scale):
            raise ValueError("scale must be finite.")
        return scale

    @staticmethod
    def snap_to_grid(x: np.ndarray, mass: np.ndarray, dx: float) -> tuple[int, np.ndarray]:
        """
        Deposit point masses at arbitrary x values onto a uniform dx grid.

        Each mass is linearly split between the two nearest grid points. This
        preserves total probability mass and avoids nearest-grid stair-step
        artifacts when projecting a distribution onto a chosen grid.

        Parameters
        ----------
        x:
            1D locations of point masses.
        mass:
            1D mass values at x; must be non-negative.
        dx:
            Target grid spacing.
        """
        dx = Pmf1D._validate_dx(dx)
        x = np.asarray(x, dtype=float)
        mass = np.asarray(mass, dtype=float)

        if x.ndim != 1 or mass.ndim != 1:
            raise ValueError("x and mass must be 1D arrays.")

        if x.shape != mass.shape:
            raise ValueError("x and mass must have the same shape.")

        if len(x) == 0:
            raise ValueError("x and mass must contain at least one point.")

        if not np.all(np.isfinite(x)):
            raise ValueError("x contains non-finite values.")

        mass = Pmf1D._validate_mass(mass)

        grid_pos = x / dx
        st_idx = int(np.floor(np.min(grid_pos)))
        end_idx = int(np.ceil(np.max(grid_pos)))
        out = np.zeros(end_idx - st_idx + 1, dtype=float)

        lo = np.floor(grid_pos).astype(int)
        frac = grid_pos - lo

        rel_lo = lo - st_idx
        np.add.at(out, rel_lo, mass * (1.0 - frac))

        hi_mask = frac > 0.0
        rel_hi = rel_lo[hi_mask] + 1
        np.add.at(out, rel_hi, mass[hi_mask] * frac[hi_mask])

        return st_idx, out

    @staticmethod
    def nearest_grid(x: np.ndarray, mass: np.ndarray, dx: float) -> tuple[int, np.ndarray]:
        """Deposit each atom at one bin, with half-grid ties away from zero."""
        dx = Pmf1D._validate_dx(dx)
        x = np.asarray(x, dtype=float)
        mass = np.asarray(mass, dtype=float)
        if x.ndim != 1 or mass.ndim != 1 or x.shape != mass.shape or x.size == 0:
            raise ValueError("x and mass must be nonempty matching 1D arrays.")
        if not np.all(np.isfinite(x)):
            raise ValueError("x contains non-finite values.")
        mass = Pmf1D._validate_mass(mass)
        positions = x / dx
        truncated = np.trunc(positions)
        indices = np.where(
            np.abs(positions - truncated) == 0.5,
            truncated + np.copysign(1.0, positions),
            np.round(positions),
        ).astype(int)
        st_idx = int(indices.min())
        out = np.zeros(int(indices.max()) - st_idx + 1, dtype=float)
        np.add.at(out, indices - st_idx, mass)
        return st_idx, out

    # --------------------------------
    # constructors
    # --------------------------------
    @classmethod
    def uniform(
        cls, delta: float, pmf_cfg: object, *, unit: str = "volt", name: str = "",
        method: Literal["bin_integral", "nearest_centers"] = "bin_integral",
        support: Optional['Pmf1D'] = None,
    ) -> 'Pmf1D':
        """
        Build a zero-mean uniform PMF over [-delta/2, delta/2).

        This constructor uses bin-integrated probability mass, consistent with
        gaussian_from_bin_integral(). It is intended for ADC quantization noise
        where the continuous quantization error is uniform over one step.

        Parameters
        ----------
        delta:
            Uniform distribution width. For quantization noise this is the ADC
            quantization step.
        pmf_cfg:
            PMF runtime/config object with a ``dy`` attribute used as the
            amplitude grid spacing.
        unit:
            Optional x-axis unit label.
        name:
            Optional PMF name for debug / plotting.
        """
        delta = float(delta)
        if not np.isfinite(delta) or delta <= 0:
            raise ValueError("delta must be a finite positive value.")

        if not hasattr(pmf_cfg, "dy"):
            raise TypeError("pmf_cfg must provide a dy attribute.")
        dx = cls._validate_dx(getattr(pmf_cfg, "dy"))

        if method == "nearest_centers":
            # Reference uniform PDF includes every grid center between the
            # nearest centers to -delta/2 and +delta/2, endpoints inclusive.
            if support is not None:
                if not np.isclose(support.dx, dx, rtol=1e-12, atol=1e-15):
                    raise ValueError("uniform support and pmf_cfg must share dx.")
                left = int(np.argmin(np.abs(support.x + delta / 2.0)))
                right = int(np.argmin(np.abs(support.x - delta / 2.0)))
                if right < left:
                    raise ValueError("uniform support cannot represent the requested interval.")
                pmf = np.zeros(len(support.pmf), dtype=float)
                pmf[left:right + 1] = 1.0 / (right - left + 1)
                return cls(
                    dx=dx, st_idx=support.st_idx, pmf=pmf,
                    unit=unit, name=name or "uniform",
                )
            half = delta / 2.0
            span = int(np.ceil(half / dx)) + 2
            candidates = np.arange(-span, span + 1)
            left = int(candidates[np.argmin(np.abs(candidates * dx + half))])
            right = int(candidates[np.argmin(np.abs(candidates * dx - half))])
            idx = np.arange(left, right + 1)
            pmf = np.full(idx.size, 1.0 / idx.size)
            return cls(dx=dx, st_idx=int(idx[0]), pmf=pmf, unit=unit, name=name or "uniform")
        if method != "bin_integral":
            raise ValueError("uniform method must be bin_integral or nearest_centers.")
        if support is not None:
            raise ValueError("uniform support is used only with nearest_centers.")

        half = 0.5 * delta
        st_idx = int(np.floor((-half - 0.5 * dx) / dx))
        end_idx = int(np.ceil((half + 0.5 * dx) / dx))
        idx = np.arange(st_idx, end_idx + 1)
        x = idx * dx

        bin_lo = x - 0.5 * dx
        bin_hi = x + 0.5 * dx
        overlap = np.maximum(0.0, np.minimum(bin_hi, half) - np.maximum(bin_lo, -half))
        keep = overlap > 0.0
        if not np.any(keep):
            raise RuntimeError("Uniform PMF construction produced no nonzero bins.")

        idx = idx[keep]
        pmf = overlap[keep] / delta
        pmf = pmf / np.sum(pmf)

        return cls(
            dx=dx,
            st_idx=int(idx[0]),
            pmf=pmf,
            unit=unit,
            name=name or "uniform",
        )

    @classmethod
    def gaussian(
        cls,
        mu: float,
        sigma: float,
        dx: float,
        *,
        n_sigma: float = 8.0,
        unit: str = "",
        name: str = "",
        method: Literal["bin_integral", "reference_sample"] = "bin_integral",
    ) -> 'Pmf1D':
        """
        Build a Gaussian PMF using bin-integrated probability mass.

        Parameters
        ----------
        mu:
            Gaussian mean.
        sigma:
            Gaussian standard deviation.
        dx:
            X-axis grid spacing.
        n_sigma:
            Truncation half-width in sigma units.
        unit:
            Optional x-axis unit label.
        name:
            Optional PMF name for debug / plotting.
        """
        if method == "reference_sample":
            return cls.gaussian_from_reference_sample(
                mu=mu, sigma=sigma, dx=dx, n_sigma=n_sigma, unit=unit, name=name,
            )
        if method != "bin_integral":
            raise ValueError("gaussian method must be bin_integral or reference_sample.")
        return cls.gaussian_from_bin_integral(
            mu=mu,
            sigma=sigma,
            dx=dx,
            n_sigma=n_sigma,
            unit=unit,
            name=name,
        )

    @classmethod
    def gaussian_from_reference_sample(
        cls, mu: float, sigma: float, dx: float, *, n_sigma: float = 8.0,
        unit: str = "", name: str = "",
    ) -> 'Pmf1D':
        """Sample the reference normal_dist grid and normalize its ordinates."""
        mu = float(mu)
        sigma = float(sigma)
        n_sigma = float(n_sigma)
        dx = cls._validate_dx(dx)
        if not np.isfinite(mu) or not np.isfinite(sigma) or sigma <= 0.0:
            raise ValueError("mu must be finite and sigma must be finite and positive.")
        if not np.isfinite(n_sigma) or n_sigma <= 0.0:
            raise ValueError("n_sigma must be finite and positive.")
        extent = int(np.floor(2.0 * n_sigma * sigma / dx + 0.5))
        center = int(np.floor(mu / dx + 0.5)) if mu >= 0 else -int(np.floor(-mu / dx + 0.5))
        indices = np.arange(center - extent, center + extent + 1)
        x = indices * dx
        pmf = np.exp(-((x - mu) ** 2) / (2.0 * sigma**2 + np.finfo(float).eps))
        pmf /= np.sum(pmf)
        return cls(dx=dx, st_idx=int(indices[0]), pmf=pmf, unit=unit, name=name)

    @classmethod
    def gaussian_from_pdf_sample(
        cls,
        mu: float,
        sigma: float,
        dx: float,
        *,
        n_sigma: float = 8.0,
        unit: str = "",
        name: str = "",
    ) -> 'Pmf1D':
        """
        Build a Gaussian PMF by sampling the PDF on grid points.

        Parameters
        ----------
        mu:
            Gaussian mean.
        sigma:
            Gaussian standard deviation.
        dx:
            X-axis grid spacing.
        n_sigma:
            Truncation half-width in sigma units.
        unit:
            Optional x-axis unit label.
        name:
            Optional PMF name for debug / plotting.
        """
        mu = float(mu)
        sigma = float(sigma)
        if not np.isfinite(sigma) or sigma <= 0:
            raise ValueError("sigma must be a finite positive value.")

        dx = cls._validate_dx(dx)
        n_sigma = float(n_sigma)
        if not np.isfinite(n_sigma) or n_sigma <= 0:
            raise ValueError("n_sigma must be a finite positive value.")

        st_idx = int(np.floor((mu - n_sigma * sigma) / dx))
        end_idx = int(np.ceil((mu + n_sigma * sigma) / dx))
        x = np.arange(st_idx, end_idx + 1) * dx
        pmf = np.exp(-0.5 * ((x - mu) / sigma) ** 2)
        pmf = pmf / np.sum(pmf)
        return cls(dx=dx, st_idx=st_idx, pmf=pmf, unit=unit, name=name)

    @classmethod
    def gaussian_from_bin_integral(
        cls,
        mu: float,
        sigma: float,
        dx: float,
        *,
        n_sigma: float = 8.0,
        unit: str = "",
        name: str = "",
    ) -> 'Pmf1D':
        """
        Build a Gaussian PMF by integrating probability over each grid bin.

        Parameters
        ----------
        mu:
            Gaussian mean.
        sigma:
            Gaussian standard deviation.
        dx:
            X-axis grid spacing.
        n_sigma:
            Truncation half-width in sigma units.
        unit:
            Optional x-axis unit label.
        name:
            Optional PMF name for debug / plotting.
        """
        mu = float(mu)
        sigma = float(sigma)
        if not np.isfinite(sigma) or sigma <= 0:
            raise ValueError("sigma must be a finite positive value.")

        dx = cls._validate_dx(dx)
        n_sigma = float(n_sigma)
        if not np.isfinite(n_sigma) or n_sigma <= 0:
            raise ValueError("n_sigma must be a finite positive value.")

        st_idx = int(np.floor((mu - n_sigma * sigma) / dx))
        end_idx = int(np.ceil((mu + n_sigma * sigma) / dx))
        x = np.arange(st_idx, end_idx + 1) * dx

        z_hi = (x + 0.5 * dx - mu) / (sigma * sqrt(2.0))
        z_lo = (x - 0.5 * dx - mu) / (sigma * sqrt(2.0))
        cdf_hi = 0.5 * (1.0 + np.vectorize(erf)(z_hi))
        cdf_lo = 0.5 * (1.0 + np.vectorize(erf)(z_lo))
        pmf = cdf_hi - cdf_lo
        pmf = pmf / np.sum(pmf)
        return cls(dx=dx, st_idx=st_idx, pmf=pmf, unit=unit, name=name)

    @classmethod
    def multi_dirac(
        cls,
        values: np.ndarray,
        probs: Optional[np.ndarray] = None,
        *,
        dx: float,
        unit: str = "",
        name: str = "",
        placement: Literal["linear", "nearest"] = "linear",
    ) -> 'Pmf1D':
        """
        Build a PMF from multiple Dirac masses.

        Parameters
        ----------
        values:
            1D x locations of Dirac masses.
        probs:
            Probability mass at each value. If None, values are equally likely.
        dx:
            X-axis grid spacing.
        unit:
            Optional x-axis unit label.
        name:
            Optional PMF name for debug / plotting.
        """
        dx = cls._validate_dx(dx)
        values = np.asarray(values, dtype=float)

        if values.ndim != 1:
            raise ValueError("values must be a 1D array.")

        if len(values) == 0:
            raise ValueError("values must contain at least one point.")

        if not np.all(np.isfinite(values)):
            raise ValueError("values contains non-finite values.")

        if probs is None:
            probs = np.full(len(values), 1.0 / len(values), dtype=float)
        else:
            probs = cls._validate_pmf(probs)
            if len(probs) != len(values):
                raise ValueError("probs must have the same length as values.")

        if placement == "nearest":
            st_idx, pmf = cls.nearest_grid(values, probs, dx)
        elif placement == "linear":
            st_idx, pmf = cls.snap_to_grid(values, probs, dx)
        else:
            raise ValueError("placement must be linear or nearest.")
        pmf = pmf / np.sum(pmf)
        return cls(dx=dx, st_idx=st_idx, pmf=pmf, unit=unit, name=name)

    # --------------------------------
    # public methods
    # --------------------------------
    def copy(self, *, name: Optional[str]=None) -> 'Pmf1D':
        """
        Return a deep copy of this PMF.

        Parameters
        ----------
        name:
            Optional name override for the copied PMF.
        """
        return Pmf1D(
            dx=self.dx,
            st_idx=self.st_idx,
            pmf=self.pmf.copy(),
            unit=self.unit,
            name=self.name if name is None else name,
        )

    def quantile(self, prob: float) -> float:
        """
        Return the x value where CDF first reaches prob.

        Parameters
        ----------
        prob:
            Target cumulative probability in [0, 1].
        """
        prob = float(prob)
        if not np.isfinite(prob) or prob < 0.0 or prob > 1.0:
            raise ValueError("prob must be finite and in [0, 1].")

        idx = int(np.searchsorted(self.cdf, prob, side="left"))
        idx = min(idx, len(self.pmf) - 1)
        return float(self.x[idx])

    def cdf_at(self, x: float | np.ndarray) -> float | np.ndarray:
        """Evaluate the right-continuous discrete CDF at one or more values.

        Each PMF entry is probability mass located at its corresponding grid
        value. Therefore ``cdf_at(y)`` returns the sum of all mass whose
        ``x <= y``. This is the value-level counterpart to :attr:`cdf` and is
        suitable for expressions such as the Annex 178A ``P_j(x_j)`` term.

        ``-inf`` and ``inf`` return 0 and 1 respectively; NaN is invalid.
        Scalar inputs return ``float`` and array-like inputs return an ndarray
        with the same shape.
        """
        values = np.asarray(x, dtype=float)
        if np.any(np.isnan(values)):
            raise ValueError("CDF evaluation points must not contain NaN.")

        indices = np.searchsorted(self.x, values, side="right") - 1
        result = np.empty(values.shape, dtype=float)
        below = indices < 0
        above = indices >= len(self.pmf)
        inside = ~(below | above)
        result[below] = 0.0
        result[above] = 1.0
        if np.any(inside):
            result[inside] = self.cdf[indices[inside]]

        if values.ndim == 0:
            return float(result)
        return result

    def shift_x(self, idx_shift: int) -> 'Pmf1D':
        """
        Return a copy with the x grid shifted by idx_shift samples.

        Probability mass values are unchanged. Only st_idx / x_st move:
            Y = X + idx_shift * dx

        Parameters
        ----------
        idx_shift:
            Integer number of grid samples to shift.
        """
        idx_shift = self._validate_st_idx(idx_shift)
        return Pmf1D(
            dx=self.dx,
            st_idx=self.st_idx + idx_shift,
            pmf=self.pmf.copy(),
            unit=self.unit,
            name=self.name,
        )

    def scale_x(
        self,
        scale: float,
        *,
        keep_dx: bool = False,
        dx_ref: Optional[float] = None,
        method: Literal["mass_deposit", "interpolate_ordinates"] = "mass_deposit",
    ) -> 'Pmf1D':
        """
        Return a copy with the x axis scaled.

        This models:
            Y = scale * X

        By default this is pure x-axis scaling and dx changes by abs(scale).
        With keep_dx=True, probability mass is projected onto dx_ref so the
        output remains on a shared grid. This is the FIR-friendly mode.

        Parameters
        ----------
        scale:
            X-axis scale factor. Negative values mirror the distribution.
        keep_dx:
            If True, deposit scaled probability mass onto dx_ref.
        dx_ref:
            Shared target grid spacing when keep_dx=True. Defaults to current
            self.dx.
        """
        scale = self._validate_scale(scale)

        if keep_dx:
            dx_ref = self.dx if dx_ref is None else self._validate_dx(dx_ref)

            if scale == 0.0:
                return Pmf1D(
                    dx=dx_ref,
                    st_idx=0,
                    pmf=np.array([np.sum(self.pmf)], dtype=float),
                    unit=self.unit,
                    name=self.name,
                )

            if method == "interpolate_ordinates":
                if scale <= 0.0:
                    raise ValueError("interpolate_ordinates requires a positive scale.")
                # Reference scalePDF uses the scaled minimum index and a
                # symmetric output grid, then interpolates PDF ordinates.
                st_pos = self.st_idx * scale * self.dx / dx_ref
                nearest_integer = np.rint(st_pos)
                if np.isclose(st_pos, nearest_integer, rtol=0.0, atol=1e-12):
                    st_pos = nearest_integer
                st_idx = int(np.floor(st_pos))
                if st_idx >= 0:
                    raise ValueError("interpolate_ordinates requires negative grid support.")
                indices = np.arange(st_idx, -st_idx + 1)
                x_out = indices * dx_ref
                pmf = np.interp(
                    x_out, self.x * scale, self.pmf, left=np.nan, right=np.nan
                )
                if pmf.size < 3:
                    raise ValueError("interpolate_ordinates requires at least three grid bins.")
                pmf[0] = pmf[1]
                pmf[-1] = pmf[-2]
                if not np.all(np.isfinite(pmf)):
                    raise ValueError("interpolate_ordinates left unsupported interior bins.")
                pmf = self._validate_pmf(pmf / np.sum(pmf))
            elif method == "mass_deposit":
                st_idx, pmf = self.snap_to_grid(scale * self.x, self.pmf, dx_ref)
            else:
                raise ValueError("scale_x method must be mass_deposit or interpolate_ordinates.")
            return Pmf1D(
                dx=dx_ref,
                st_idx=st_idx,
                pmf=self._validate_pmf(pmf),
                unit=self.unit,
                name=self.name,
            )

        if dx_ref is not None:
            raise ValueError("dx_ref is only used when keep_dx=True.")

        if scale == 0.0:
            return Pmf1D(
                dx=self.dx,
                st_idx=0,
                pmf=np.array([np.sum(self.pmf)], dtype=float),
                unit=self.unit,
                name=self.name,
            )

        st_idx = self.st_idx
        pmf = self.pmf.copy()
        if scale < 0.0:
            st_idx = -(self.st_idx + len(self.pmf) - 1)
            pmf = pmf[::-1].copy()

        return Pmf1D(
            dx=self.dx * abs(scale),
            st_idx=st_idx,
            pmf=self._validate_pmf(pmf),
            unit=self.unit,
            name=self.name,
        )

    def resample_dx(self, dx_new: float, *, name: Optional[str]=None) -> 'Pmf1D':
        """
        Return a copy projected to a new x-grid spacing.

        This keeps the same random variable and only changes the PMF
        representation grid. Probability mass at each existing x location is
        linearly deposited onto the nearest points of the dx_new grid.

        Parameters
        ----------
        dx_new:
            New target grid spacing.
        name:
            Optional name override after resampling.
        """
        dx_new = self._validate_dx(dx_new)
        st_idx, pmf = self.snap_to_grid(self.x, self.pmf, dx_new)
        return Pmf1D(
            dx=dx_new,
            st_idx=st_idx,
            pmf=self._validate_pmf(pmf),
            unit=self.unit,
            name=self.name if name is None else name,
        )

    def fir_filter(
        self,
        fir: np.ndarray,
        *,
        keep_mass: float = float(1-1e-5),
        dx_ref: Optional[float] = None,
        tap_abs_th: float = 0.0,
        max_taps: Optional[int] = None,
        name: Optional[str] = None,
        scaling_method: Literal["mass_deposit", "interpolate_ordinates"] = "mass_deposit",
        initial_bin_range: Optional[tuple[int, int]] = None,
    ) -> 'Pmf1D':
        """
        Return the FIR-filtered PMF.

        If self represents the symbol distribution X, this method returns the
        distribution of:
            Y = sum_i fir[i] * X_i

        The X_i are treated as independent random variables with the original
        self distribution. Each tap-scaled PMF is projected to dx_ref before
        convolution so all terms share one representation grid.

        Parameters
        ----------
        fir:
            1D FIR tap coefficients.
        keep_mass:
            Probability mass to keep after each convolution.
        dx_ref:
            Shared grid spacing for each tap contribution. Defaults to self.dx.
        tap_abs_th:
            Absolute tap threshold. Keep taps with abs(tap) >= tap_abs_th.
        max_taps:
            Maximum number of strongest taps to keep.
        name:
            Optional name override after filtering.
        scaling_method:
            Project scaled probability masses or interpolate gridded ordinates.
        initial_bin_range:
            Optional inclusive support of the unit-mass seed on ``dx_ref``.
            Only the zero bin has mass; other bins retain the supplied support
            during subsequent convolutions.
        """
        coeff = _prune_fir_coeff(fir, tap_abs_th=tap_abs_th, max_taps=max_taps)
        dx_ref = self.dx if dx_ref is None else self._validate_dx(dx_ref)

        if len(coeff) == 0:
            if initial_bin_range is None:
                first, last = 0, 0
            else:
                first, last = (int(value) for value in initial_bin_range)
                if first > 0 or last < 0 or last < first:
                    raise ValueError("initial_bin_range must contain zero.")
            unit_mass = np.zeros(last - first + 1, dtype=float)
            unit_mass[-first] = 1.0
            filtered = Pmf1D(
                dx=dx_ref,
                st_idx=first,
                pmf=unit_mass,
                unit=self.unit,
                name=self.name if name is None else name,
            )
        else:
            base = self.copy()

            if initial_bin_range is None:
                out_st_idx = 0
                out_pmf = np.array([1.0], dtype=float)
            else:
                first, last = (int(value) for value in initial_bin_range)
                if first > 0 or last < 0 or last < first:
                    raise ValueError("initial_bin_range must contain zero.")
                out_st_idx = first
                out_pmf = np.zeros(last - first + 1, dtype=float)
                out_pmf[-first] = 1.0

            for c in coeff:
                term = base.copy().scale_x(
                    abs(c) if scaling_method == "interpolate_ordinates" else c,
                    keep_dx=True, dx_ref=dx_ref, method=scaling_method,
                )
                out_pmf = _convolve_probability_mass(out_pmf, term.pmf)
                out_st_idx += term.st_idx

                if keep_mass < 1.0:
                    tmp = Pmf1D(dx=dx_ref, st_idx=out_st_idx, pmf=out_pmf, unit=self.unit)
                    tmp = _truncate_keep_mass(tmp, keep_mass=keep_mass)
                    out_st_idx = tmp.st_idx
                    out_pmf = tmp.pmf

            filtered = Pmf1D(
                dx=dx_ref,
                st_idx=out_st_idx,
                pmf=out_pmf,
                unit=self.unit,
                name=self.name if name is None else name,
            )

        return filtered

    @classmethod
    def fir_filter_atoms(
        cls, values: np.ndarray, probs: np.ndarray, fir: np.ndarray, *, dx: float,
        keep_mass: float = float(1 - 1e-5), tap_abs_th: float = 0.0,
        max_taps: Optional[int] = None, unit: str = "", name: str = "",
    ) -> 'Pmf1D':
        """Convolve FIR terms formed directly from unquantized source atoms.

        Every ``fir[i] * values`` term is placed on the target grid once.
        This preserves the source amplitudes until after tap multiplication.
        """
        coeff = _prune_fir_coeff(fir, tap_abs_th=tap_abs_th, max_taps=max_taps)
        dx = cls._validate_dx(dx)
        out = cls.multi_dirac(
            np.array([0.0]), np.array([1.0]), dx=dx, unit=unit,
            name=name, placement="nearest",
        )
        for c in coeff:
            term = cls.multi_dirac(
                c * np.asarray(values, dtype=float), probs, dx=dx,
                unit=unit, placement="nearest",
            )
            out = out.combine(term, name=name)
            if keep_mass < 1.0:
                out = _truncate_keep_mass(out, keep_mass=keep_mass)
        return out

    def combine(self, other: 'Pmf1D', *, name: Optional[str]=None) -> 'Pmf1D':
        """
        Return the convolution with another independent PMF.

        If self represents X and other represents Y, this method returns the
        distribution of:
            Z = X + Y

        Both PMFs must already use the same dx. Use resample_dx() explicitly
        before combine() when grid alignment is required.

        Parameters
        ----------
        other:
            Independent PMF to add to self.
        name:
            Optional name override after convolution.
        """
        if not isinstance(other, Pmf1D):
            raise TypeError("other must be a Pmf1D.")

        if not np.isclose(self.dx, other.dx, rtol=1e-12, atol=1e-15):
            raise ValueError("Cannot combine PMFs with different dx. Resample to a shared grid first.")

        if self.unit and other.unit and self.unit != other.unit:
            raise ValueError("Cannot combine PMFs with different non-empty units.")

        return Pmf1D(
            dx=self.dx,
            st_idx=self.st_idx + other.st_idx,
            pmf=self._validate_pmf(_convolve_probability_mass(self.pmf, other.pmf)),
            unit=self.unit or other.unit,
            name=self.name if name is None else name,
        )


