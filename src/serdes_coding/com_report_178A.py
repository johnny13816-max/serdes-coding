    def _plot_imp_stage(
        self,
        stage: COMImpStageStatus,
        directory_name: str,
        root: str | Path,
        *,
        pre_dte: bool,
    ) -> dict[str, str]:
        directory = str(Path(root) / directory_name) if root else ""
        outputs: dict[str, str] = {}

        if stage.psd is not None:
            names = ("S_rn", "S_xn", "S_tn", "S_jn", "S_qn", "S_total")
            psd_values = [(name, getattr(stage.psd, name)) for name in names if getattr(stage.psd, name) is not None]
            if psd_values:
                outputs["psd"] = self._plot_psd_group(psd_values, directory, "psd_components.png", f"{directory_name} PSD")

        outputs["imp_proportion"] = self._plot_imp_proportion(stage, directory, directory_name, pre_dte=pre_dte)

        if stage.eq_ch is not None:
            eq = stage.eq_ch
            primary = [("h_dsamp", eq.h_dsamp), ("h_tn", eq.h_tn), ("h_J", eq.h_J)] if pre_dte else [("h_w", eq.h_w), ("h_ISI", eq.h_ISI), ("h_w_J", eq.h_w_J)]
            reference_index = (
                int(self.status.dfe.d) - int(self.cfg.dte.d_w)
                if pre_dte and self.status.dfe is not None
                else int(self.status.dfe.d)
                if not pre_dte and self.status.dfe is not None
                else None
            )
            for name, values in primary:
                if values is not None:
                    outputs[name] = self._plot_sequence(
                        values,
                        directory,
                        f"{name}.png",
                        f"{directory_name} {name}",
                        f"{name} (V)",
                        reference_index=reference_index,
                    )
            xtalk_name, xtalk_values = ("h_XTs_dsamp", eq.h_XTs_dsamp) if pre_dte else ("h_XTs_w", eq.h_XTs_w)
            if xtalk_values:
                outputs[xtalk_name] = self._plot_sequence_group(
                    xtalk_values,
                    directory,
                    f"{xtalk_name}.png",
                    f"{directory_name} {xtalk_name}",
                    reference_index=reference_index,
                )

        if stage.adc_input is not None:
            outputs.update(self._plot_adc_input(stage.adc_input, directory, f"{directory_name} ADC Input"))
        return outputs

    def _plot_imp_proportion(
        self,
        stage: COMImpStageStatus,
        directory: str,
        stage_name: str,
        *,
        pre_dte: bool,
    ) -> str:
        """Plot impairment variance contributions for one processing stage."""
        contributions: list[tuple[str, float]] = []
        if pre_dte and stage.psd is not None:
            for name, label in (
                ("sigma_rn", "receiver noise"),
                ("sigma_xn", "crosstalk"),
                ("sigma_tn", "TX noise"),
                ("sigma_jn", "TX jitter"),
                ("sigma_qn", "ADC quantization"),
            ):
                value = getattr(stage.psd, name, None)
                if value is not None:
                    contributions.append((label, float(value)))
        elif not pre_dte:
            if stage.psd is not None and stage.psd.sigma_ISI is not None:
                contributions.append(("ISI", float(stage.psd.sigma_ISI)))
            adc = stage.adc_input
            if adc is not None:
                for name, label in (("p_XT", "crosstalk"), ("p_DD", "DDJ"), ("p_ga", "Gaussian noise")):
                    pmf = getattr(adc, name, None)
                    if pmf is not None:
                        _, std = self._pmf_moments(pmf)
                        contributions.append((label, std))

        contributions = [(label, sigma) for label, sigma in contributions if np.isfinite(sigma) and sigma >= 0.0]
        if not contributions or not any(sigma > 0.0 for _, sigma in contributions):
            return ""

        labels = [label for label, _ in contributions]
        variance = np.asarray([sigma**2 for _, sigma in contributions], dtype=float)
        percentages = 100.0 * variance / np.sum(variance)
        fig, ax, output = self._subplots(directory, "imp_proportion.png", figsize=(7, 4))
        bars = ax.bar(labels, percentages, color="tab:blue")
        for bar, percentage in zip(bars, percentages):
            ax.text(
                bar.get_x() + bar.get_width() / 2.0,
                bar.get_height(),
                f"{percentage:.1f}%",
                ha="center",
                va="bottom",
                fontsize=9,
            )
        ax.set_ylabel("Variance contribution (%)")
        ax.set_ylim(0.0, max(100.0, float(np.max(percentages)) * 1.18))
        ax.grid(axis="y", alpha=0.35)
        self._title(ax, f"{stage_name} Impairment Proportion", "Percentage of total impairment variance")
        self._annotate_imp_config(ax)
        self._finish(fig, output)
        return output

    def _plot_psd_group(self, psds: list[tuple[str, Any]], directory: str, filename: str, title: str) -> str:
        fig, ax, output = self._subplots(directory, filename)
        for name, psd in psds:
            psd.plot(ax=ax, label=name)
        values = np.concatenate([np.asarray(psd.psd) for _, psd in psds])
        positive_values = values[np.isfinite(values) & (values > 0.0)]
        if positive_values.size:
            ax.set_yscale("log")
            max_value = float(np.max(positive_values))
            min_value = float(np.min(positive_values))
            # Keep a readable logarithmic window without letting numerical
            # noise or isolated tiny bins determine the whole axis.
            lower = max(0.5 * min_value, max_value * 1e-12)
            upper = 2.0 * max_value
            ax.set_ylim(lower, upper)
        self._title(ax, title, "One-sided sampled PSD; CT-equivalent frequency axis")
        self._annotate_config(ax)
        self._finish(fig, output)
        return output

    def _plot_sequence(
        self,
        values: np.ndarray,
        directory: str,
        filename: str,
        title: str,
        ylabel: str,
        *,
        reference_index: Optional[int] = None,
    ) -> str:
        values = np.asarray(values, dtype=float)
        reference = int(np.argmax(np.abs(values))) if reference_index is None else int(reference_index)
        x = (np.arange(len(values)) - reference).astype(float)
        fig, ax, output = self._subplots(directory, filename)
        ax.stem(x, values, basefmt=" ")
        ax.axvline(0.0, color="tab:green", linestyle="--", linewidth=0.8)
        ax.set_xlabel("Discrete time (UI, selected victim cursor = 0)")
        ax.set_ylabel(ylabel)
        ax.set_xlim(-5.0, 20.0)
        ax.grid(True)
        self._title(ax, title)
        self._annotate_config(ax)
        self._finish(fig, output)
        return output

    def _plot_sequence_group(
        self,
        values: list[np.ndarray],
        directory: str,
        filename: str,
        title: str,
        *,
        reference_index: Optional[int] = None,
    ) -> str:
        fig, ax, output = self._subplots(directory, filename)
        for idx, sequence in enumerate(values):
            sequence = np.asarray(sequence, dtype=float)
            reference = int(np.argmax(np.abs(sequence))) if reference_index is None else int(reference_index)
            ax.plot(np.arange(len(sequence)) - reference, sequence, label=f"XT[{idx}]")
        ax.set_xlabel("Discrete time (UI, selected victim cursor = 0)")
        ax.set_ylabel("Amplitude (V)")
        ax.set_xlim(-5.0, 20.0)
        ax.grid(True)
        ax.legend()
        self._title(ax, title)
        self._annotate_config(ax)
        self._finish(fig, output)
        return output

    def _plot_adc_input(self, adc: COMAdcInputPMF, directory: str, title: str) -> dict[str, str]:
        """Plot ADC clipping inputs without overlaying incompatible PMF scales."""
        if adc.method != "pmf_exact":
            return {}

        outputs: dict[str, str] = {}
        fig, axes, output = self._subplots(directory, "adc_input_components.png", 2, 1, figsize=(7, 7), sharex=False)
        p_n = adc.p_n if adc.p_n is not None else adc.p_ga
        if adc.p_s is not None:
            adc.p_s.plot(ax=axes[0], label="p_s")
        if p_n is not None:
            p_n.plot(ax=axes[1], label="p_n")
        self._title(axes[0], f"{title}: signal PMF")
        self._title(axes[1], f"{title}: noise PMF")
        self._annotate_pmf_config(axes[1], adc)
        self._finish(fig, output)
        outputs["adc_input_components"] = output

        fig, axes, output = self._subplots(directory, "adc_input_distribution.png", 2, 1, figsize=(7, 7), sharex=True)
        pdf_ax, cdf_ax = axes
        if adc.p_sn is not None:
            adc.p_sn.plot(ax=pdf_ax, label="p_sn")
            adc.p_sn.plot(ax=cdf_ax, quantity="cdf", label="CDF(p_sn)")

        if adc.V_qc is not None:
            p_qc = self.cfg.imp.P_qc
            for ax in axes:
                ax.axvline(-adc.V_qc, color="tab:red", linestyle="--", linewidth=1.0)
                ax.axvline(adc.V_qc, color="tab:red", linestyle="--", linewidth=1.0)
            pdf_ax.annotate(
                f"V_qc={adc.V_qc:.4g} V\nP_qc={p_qc:.3e}" if p_qc is not None else f"V_qc={adc.V_qc:.4g} V",
                xy=(adc.V_qc, 0.98),
                xycoords=("data", "axes fraction"),
                xytext=(-6, -6),
                textcoords="offset points",
                ha="right",
                va="top",
                color="tab:red",
                fontsize=9,
                bbox={"boxstyle": "round,pad=0.25", "facecolor": "white", "edgecolor": "tab:red", "alpha": 0.9},
            )
            if adc.p_sn is not None:
                cdf_neg = float(np.interp(-adc.V_qc, adc.p_sn.x, adc.p_sn.cdf))
                cdf_ax.scatter([-adc.V_qc], [cdf_neg], color="tab:red", zorder=3)
                cdf_ax.annotate(
                    f"CDF(-V_qc)={cdf_neg:.3e}",
                    xy=(-adc.V_qc, cdf_neg),
                    xytext=(8, 8),
                    textcoords="offset points",
                    ha="left",
                    color="tab:red",
                    fontsize=8,
                )
        cdf_ax.set_ylim(-0.02, 1.02)
        self._title(pdf_ax, f"{title}: p_sn PDF", f"method={adc.method}, delta={adc.delta}")
        self._title(cdf_ax, "p_sn CDF and ADC clipping threshold")
        self._annotate_pmf_config(cdf_ax, adc)
        cdf_ax.set_yscale("log")
        cdf_ax.set_ylim(max(1e-12, float(np.min(adc.p_sn.cdf)) if adc.p_sn is not None else 1e-12), 1.0)
        self._finish(fig, output)
        outputs["adc_input_distribution"] = output
        return outputs

    # ------------------------------------------------------------------
    # calculate_COM_DFE: COMPMFStatus
    # ------------------------------------------------------------------
    def plot_pmf(self, save_path: str | Path = "") -> dict[str, str]:
        """Plot final COM DFE PMF components and the combined CDF tail."""
        if self.status.pmf is None:
            raise ValueError("COMStatus.pmf is not available.")
        pmf_status = self.status.pmf
        directory = str(Path(save_path) / "pmf") if save_path else ""
        outputs: dict[str, str] = {}

        components = [
            (name, getattr(pmf_status, name))
            for name in ("p_ISI", "p_G", "p_DD", "p_XT", "p_qn")
            if getattr(pmf_status, name) is not None
        ]

        for name, pmf in components:
            fig, ax, output = self._subplots(directory, f"{name}.png")
            pmf.plot(ax=ax, label=name)
            mu, std = self._pmf_moments(pmf)
            self._title(ax, name, f"mu={mu:.3e} V, std={std:.3e} V")
            self._annotate_pmf_settings(ax, pmf)
            self._finish(fig, output)
            outputs[name] = output

        fig, ax, output = self._subplots(directory, "pmf_components.png")
        for name, pmf in components:
            pmf.plot(ax=ax, label=name)
        self._title(ax, "Final PMF Components")
        if components:
            self._annotate_pmf_settings(ax, components[0][1])
        self._finish(fig, output)
        outputs["components"] = output

        if pmf_status.p_combined is not None:
            total = pmf_status.p_combined
            fig, axes, output = self._subplots(directory, "combined_cdf.png", 2, 1, figsize=(7, 7), sharex=True)
            pdf_ax, cdf_ax = axes
            total.plot(ax=pdf_ax, label="p_total")
            total.plot(ax=cdf_ax, quantity="cdf", label="CDF(p_total)")

            der0 = float(self.cfg.DER_0)
            y0 = float(total.quantile(der0))
            p_total_y0 = float(np.interp(y0, total.x, total.pmf))
            for axis in axes:
                axis.axvline(y0, color="tab:red", linestyle="--", linewidth=1.0)

            pdf_ax.scatter([y0], [p_total_y0], color="tab:red", zorder=3)
            pdf_ax.annotate(
                f"A_ni={abs(y0):.3e} V",
                xy=(y0, p_total_y0),
                xytext=(8, 8),
                textcoords="offset points",
                color="tab:red",
                fontsize=8,
            )
            cdf_ax.scatter([y0], [der0], color="tab:red", zorder=3)
            cdf_ax.annotate(
                f"DER_0={der0:.3e}\nA_ni={abs(y0):.3e} V",
                xy=(y0, der0),
                xytext=(8, 8),
                textcoords="offset points",
                color="tab:red",
                fontsize=8,
            )
            if pmf_status.y0 is not None:
                cdf_ax.axhline(der0, color="tab:red", linestyle=":", linewidth=0.8)
            cdf_values = np.asarray(total.cdf, dtype=float)
            positive_cdf = cdf_values[np.isfinite(cdf_values) & (cdf_values > 0.0)]
            cdf_ax.set_yscale("log")
            cdf_lower = max(
                1.0e-12,
                float(np.min(positive_cdf)) * 0.5 if positive_cdf.size else 1.0e-12,
            )
            cdf_ax.set_ylim(cdf_lower, 1.0)
            com_text = (
                f"COM={pmf_status.COM:.3f} dB"
                if pmf_status.COM is not None
                else "COM=None"
            )
            self._title(
                pdf_ax,
                "Total PMF PDF",
                f"{com_text}, DER_0={der0:.3e}, A_ni={abs(y0):.3e} V",
            )
            self._title(cdf_ax, "Total PMF CDF", f"{com_text}, DER_0 threshold")
            self._annotate_pmf_settings(cdf_ax, total)
            self._finish(fig, output)
            outputs["combined_cdf"] = output
        return outputs

