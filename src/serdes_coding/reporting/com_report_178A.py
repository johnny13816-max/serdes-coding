    # ------------------------------------------------------------------
    # sampling-phase sweep / MMSE-DTE: COMRunStatus + COMDTEStatus
    # ------------------------------------------------------------------
    def plot_phase_dte(self, save_path: str | Path = "") -> dict[str, str]:
        """Plot sampling-phase selection and selected MMSE-DTE fields."""
        if self.status.dte is None or self.status.run is None:
            raise ValueError("COMStatus.run and COMStatus.dte are required for DTE reporting.")
        dte = self.status.dte
        out_dir = str(Path(save_path) / "equalization") if save_path else ""
        outputs: dict[str, str] = {}

        fig, ax, output = self._subplots(out_dir, "mse_by_pos.png")
        run = self.status.run
        mse = np.asarray([np.nan if value is None else value for value in run.mse_by_pos], dtype=float)
        pos = np.arange(len(mse))
        coarse_pos = np.asarray(run.coarse_pos, dtype=int)
        fine_pos = np.asarray(run.fine_pos, dtype=int)
        if fine_pos.size:
            coarse_valid = coarse_pos[np.isfinite(mse[coarse_pos])]
            fine_valid = fine_pos[np.isfinite(mse[fine_pos])]
            if coarse_valid.size:
                ax.plot(
                    coarse_valid, mse[coarse_valid], marker="o", linewidth=1.0,
                    color="tab:blue", label="coarse MSE",
                )
            if fine_valid.size:
                ax.plot(
                    fine_valid, mse[fine_valid], marker="s", linewidth=1.0,
                    color="tab:orange", label="fine MSE",
                )
        else:
            valid = np.isfinite(mse)
            ax.plot(pos[valid], mse[valid], marker="o", linewidth=1.0, label="valid MSE")
        invalid = np.asarray([message is not None for message in self.status.run.main_cursor_error_by_pos])
        if np.any(invalid):
            y_mark = np.nanmax(mse) if np.any(np.isfinite(mse)) else 0.0
            ax.scatter(
                pos[invalid], np.full(np.count_nonzero(invalid), y_mark),
                marker="x", color="tab:red", label="main-cursor error",
            )
        ax.axvline(dte.pos, color="tab:green", linestyle="--", label=f"selected pos={dte.pos}")
        ax.set_xlabel("Sampling phase pos")
        ax.set_ylabel("MMSE (V^2)")
        ax.grid(True)
        ax.legend()
        sweep_description = (
            "Coarse phase sweep followed by fine search"
            if fine_pos.size
            else "MSE is minimized over valid phases only"
        )
        subtitle = f"{sweep_description}; final MSE={float(dte.mse):.6e} V^2"
        self._title(ax, "Sampling Phase Search", subtitle)
        self._annotate_config(ax)
        self._finish(fig, output)
        outputs["mse_by_pos"] = output

        pre = self.status.imp.pre_dte if self.status.imp is not None else None
        eq_ch = self.status.imp.eq_ch if self.status.imp is not None else None
        if pre is not None and eq_ch is not None and eq_ch.h_dsamp is not None:
            victim_pulse = self.status.paths[0].pulse if self.status.paths else None
            if victim_pulse is not None:
                outputs["h_dsamp"] = self._plot_pulse_and_h_dsamp(
                    victim_pulse.ir,
                    eq_ch.h_dsamp.ir,
                    dte,
                    out_dir,
                )
            else:
                outputs["h_dsamp"] = self._plot_sequence(
                    eq_ch.h_dsamp.ir,
                    out_dir,
                    "h_dsamp.png",
                    "Selected h_dsamp",
                    "h_dsamp (V)",
                    reference_index=int(dte.d) - int(self.cfg.dte.d_w),
                )

        if eq_ch is not None and eq_ch.h_ISI is not None:
            outputs["h_ISI"] = self._plot_sequence(
                eq_ch.h_ISI.ir if isinstance(eq_ch.h_ISI, SampledResponse) else eq_ch.h_ISI,
                out_dir,
                "h_ISI.png",
                "Residual ISI Samples",
                "h_ISI (V)",
                reference_index=int(dte.d),
            )

        outputs["coefficients"] = self._plot_dte_coefficients(dte, out_dir)
        outputs["mmse_matrices"] = self._plot_dte_matrices(dte, out_dir)
        return outputs

